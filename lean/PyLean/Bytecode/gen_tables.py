"""Generate Opcode.lean from CPython's headers.

    python3 lean/PyLean/Bytecode/gen_tables.py <cpython-3.15 checkout> > lean/PyLean/Bytecode/Opcode.lean

The tables are transcribed mechanically so that nothing in them is typed by hand:
opcode numbers from Include/opcode_ids.h, `_PyOpcode_num_popped`/`_pushed`,
`_PyOpcode_Caches`, `_PyOpcode_Deopt`, and the HAS_*_FLAG bits from
Include/internal/pycore_opcode_metadata.h.
"""

import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
ids = (root / "Include/opcode_ids.h").read_text()
meta = (root / "Include/internal/pycore_opcode_metadata.h").read_text()

ops = {}
for name, num in re.findall(r"#define (\w+)\s+(\d+)\s*$", ids, re.M):
    if name in ("HAVE_ARGUMENT", "MIN_SPECIALIZED_OPCODE", "MIN_INSTRUMENTED_OPCODE"):
        continue
    if int(num) < 256:
        ops[name] = int(num)
order = sorted(ops, key=ops.get)


def table(fn):
    body = meta[meta.index(f"int {fn}(int opcode, int oparg)  {{"):]
    body = body[: body.index("default:")]
    return dict(re.findall(r"case (\w+):\s*return ([^;]+);", body))


def c_expr(e):
    e = e.strip()
    e = e.replace("oparg", "a").replace("0xFF", "255")
    e = re.sub(r"\ba>>8\b", "(a >>> 8)", e)
    e = e.replace(">>", ">>>").replace(">>>>", ">>>")
    e = e.replace("&", "&&&").replace("&&&&&&", "&&&")
    return e


popped, pushed = table("_PyOpcode_num_popped"), table("_PyOpcode_num_pushed")
caches = dict(re.findall(r"\[(\w+)\] = (\d+),", meta[meta.index("_PyOpcode_Caches[256] = {"):
                                                      meta.index("_PyOpcode_Deopt[256]")]))
deopt_src = meta[meta.index("const uint8_t _PyOpcode_Deopt[256] = {"):]
deopt_src = deopt_src[: deopt_src.index("};")]
deopt = dict(re.findall(r"\[(\w+)\] = (\w+),", deopt_src))
flags_src = meta[meta.index("_PyOpcode_opcode_metadata[267] = {"):]
flags_src = flags_src[: flags_src.index("};")]
flags = dict(re.findall(r"\[(\w+)\] = \{ [^,]*, [^,]*, ([^}]*?) \},", flags_src))

out = []
w = out.append
w("""/-!
Opcode numbers and static metadata of CPython 3.15.2, generated by `gen_tables.py`
from `Include/opcode_ids.h` and `Include/internal/pycore_opcode_metadata.h`.
Nothing here is typed by hand. Pseudo-instructions (numbers >= 256) never reach
the interpreter and are left out.
-/

namespace PyLean.Bytecode
""")
w("/-- Every real opcode of 3.15.2, specialized and instrumented forms included. -/")
w("inductive Op where")
for n in order:
    w(f"  | {n}")
w("  deriving DecidableEq, Inhabited, Repr\n")

w("/-- `Include/opcode_ids.h`. -/")
w("def Op.toNat : Op → Nat")
for n in order:
    w(f"  | .{n} => {ops[n]}")
w("")
w("/-- Opcodes indexed by number; `none` for the holes in the numbering. -/")
w("def opTable : Array (Option Op) := #[")
by_num = {v: k for k, v in ops.items()}
rows = [(f"some .{by_num[i]}" if i in by_num else "none") for i in range(256)]
for i in range(0, 256, 4):
    w("  " + ", ".join(rows[i:i + 4]) + ("," if i + 4 < 256 else ""))
w("]\n")
w("def Op.ofNat? (n : Nat) : Option Op := (opTable[n]?).join\n")
w("/-- `_PyOpcode_Caches`: inline cache entries after the instruction (0 when absent). -/")
w("def Op.caches : Op → Nat")
for n in order:
    if n in caches:
        w(f"  | .{n} => {caches[n]}")
w("  | _ => 0\n")
# _PyOpcode_Caches is indexed by generic opcodes only; the generated `next_instr +=`
# of a specialized form is given by its family.
w("/-- `_PyOpcode_Deopt`: the generic form of an opcode. -/")
w("def Op.deopt : Op → Op")
for n in order:
    if n in deopt and deopt[n] != n:
        w(f"  | .{n} => .{deopt[n]}")
w("  | o => o\n")
w("/-- `_PyOpcode_num_popped`. C `int` arithmetic on `oparg`; every `oparg-1` in the")
w("table is guarded by `assert(oparg > 0)` in `Python/bytecodes.c`. -/")
w("def numPopped (o : Op) (a : Nat) : Nat :=\n  match o with")
for n in order:
    e = popped.get(n)
    w(f"  | .{n} => {c_expr(e) if e is not None else 0}")
w("")
w("/-- `_PyOpcode_num_pushed`. -/")
w("def numPushed (o : Op) (a : Nat) : Nat :=\n  match o with")
for n in order:
    e = pushed.get(n)
    w(f"  | .{n} => {c_expr(e) if e is not None else 0}")
w("")
for fl, nm in [("HAS_JUMP_FLAG", "hasJump"), ("HAS_ARG_FLAG", "hasArg"),
               ("HAS_DEOPT_FLAG", "hasDeopt"), ("HAS_EXIT_FLAG", "hasExit"),
               ("HAS_ERROR_FLAG", "hasError"), ("HAS_ERROR_NO_POP_FLAG", "hasErrorNoPop")]:
    w(f"/-- `{fl}` in `_PyOpcode_opcode_metadata`. -/")
    w(f"def Op.{nm} : Op → Bool")
    for n in order:
        if fl in flags.get(n, ""):
            w(f"  | .{n} => true")
    w("  | _ => false\n")
w("end PyLean.Bytecode")
print("\n".join(out))
