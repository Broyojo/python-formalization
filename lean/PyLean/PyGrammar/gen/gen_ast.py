#!/usr/bin/env python3
"""Generate lean/PyLean/PyGrammar/AstGen.lean from Parser/Python.asdl and Grammar/Tokens.

Nothing in the output is hand transcribed: the ASDL file is read with CPython's
own `Parser/asdl.py`. Run with no argument to rewrite the file, or with `--check`
to fail if the committed file differs from what the sources generate.
"""

import os
import sys
from pathlib import Path

V = Path(os.environ.get("CPYTHON_SRC", Path(__file__).resolve().parents[4] / "vendor" / "cpython-3.15"))
if not V.exists():
    V = Path.home() / "pf" / "vendor" / "cpython-3.15"
sys.path.insert(0, str(V / "Parser"))
import asdl  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "AstGen.lean"

BUILTIN = {"identifier": "identifier", "int": "int", "string": "string", "constant": "constant"}


def lean_ctor(name):
    return name


def main():
    mod = asdl.parse(str(V / "Parser" / "Python.asdl"))
    ctors = []  # (name, sumtype or None, fields, attrs)
    types = []
    for d in mod.dfns:
        types.append(d.name)
        v = d.value
        attrs = [(a.name, a.type, a.opt) for a in getattr(v, "attributes", [])]
        if isinstance(v, asdl.Sum):
            for c in v.types:
                ctors.append((c.name, d.name, c.fields, attrs))
        else:
            ctors.append((d.name + "_", d.name, v.fields, attrs))

    out = []
    w = out.append
    w("/-! GENERATED by `gen/gen_ast.py` from `Parser/Python.asdl` and `Grammar/Tokens`. Do not edit. -/")
    w("")
    w("namespace PyLean.PyGrammar")
    w("")
    w("/-- One constructor per ASDL constructor; a product type `t` becomes `t_`.")
    w("The `P…` constructors are parser-internal records (`Parser/pegen.h`). -/")
    w("inductive Ctor where")
    for name, _, _, _ in ctors:
        w(f"  | {lean_ctor(name)}")
    for name in ["PCmpopExprPair", "PKeyValuePair", "PKeyPatternPair", "PNameDefaultPair",
                 "PSlashWithDefault", "PStarEtc", "PAugOperator", "PKeywordOrStarred",
                 "PResultTokenWithMetadata", "PDummy"]:
        w(f"  | {name}")
    w("  deriving DecidableEq, Repr, Inhabited")
    w("")
    w("/-- ASDL builtin or node type of a field. -/")
    w("inductive FieldBase where")
    w("  | identifier | int | string | constant")
    for t in types:
        w(f"  | {t}_")
    w("  deriving DecidableEq, Repr")
    w("")
    w("/-- ASDL field quantifier. -/")
    w("inductive FieldQuant where")
    w("  | one | opt | seq | optSeq")
    w("  deriving DecidableEq, Repr")
    w("")
    w("/-- The Python class name of a constructor (`_ast.<name>`). -/")
    w("def Ctor.name : Ctor → String")
    for name, sumt, _, _ in ctors:
        w(f'  | .{lean_ctor(name)} => "{name[:-1] if name.endswith("_") else name}"')
    w('  | _ => "<internal>"')
    w("")
    w("/-- Inverse of `Ctor.name`. -/")
    w("def Ctor.ofName? : String → Option Ctor")
    for name, sumt, _, _ in ctors:
        w(f'  | "{name[:-1] if name.endswith("_") else name}" => some .{lean_ctor(name)}')
    w("  | _ => none")
    w("")
    w("/-- The ASDL sum or product a constructor belongs to. -/")
    w("def Ctor.asdlType? : Ctor → Option FieldBase")
    for name, sumt, _, _ in ctors:
        w(f"  | .{lean_ctor(name)} => some .{sumt}_")
    w("  | _ => none")
    w("")

    def fb(t):
        return "." + (BUILTIN.get(t) or (t + "_"))

    def fq(f):
        if f.seq and f.opt:
            return ".optSeq"
        if f.seq:
            return ".seq"
        if f.opt:
            return ".opt"
        return ".one"

    w("/-- One ASDL field. -/")
    w("abbrev fld (n : String) (b : FieldBase) (q : FieldQuant) : String × FieldBase × FieldQuant := (n, b, q)")
    w("")
    w("/-- Fields of a constructor in ASDL order: `(name, base type, quantifier)`. -/")
    w("def Ctor.fields : Ctor → _root_.List (String × FieldBase × FieldQuant)")
    for name, _, fields, _ in ctors:
        fs = ", ".join(f'fld "{f.name}" {fb(str(f.type))} {fq(f)}' for f in fields)
        w(f"  | .{lean_ctor(name)} => [{fs}]")
    w("  | _ => []")
    w("")
    w("/-- Whether the constructor carries `lineno, col_offset, end_lineno, end_col_offset`. -/")
    w("def Ctor.hasLoc : Ctor → Bool")
    for name, _, _, attrs in ctors:
        if attrs:
            w(f"  | .{lean_ctor(name)} => true")
    w("  | _ => false")
    w("")
    w("/-- Every ASDL constructor, in file order. -/")
    w("def Ctor.all : _root_.List Ctor :=")
    w("  [" + ", ".join("Ctor." + lean_ctor(n) for n, _, _, _ in ctors) + "]")
    w("")

    # Tokens, numbered as in Include/internal/pycore_token.h.
    names, exact = [], {}
    for line in (V / "Grammar" / "Tokens").read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        parts = line.split()
        names.append(parts[0])
        if len(parts) > 1:
            exact[parts[0]] = parts[1].strip("'")
    # COMMENT, NL and the rest appear at the end of the file as plain names.
    w("/-- `Grammar/Tokens`, in file order; `TokKind.num` is the C token number. -/")
    w("inductive TokKind where")
    for n in names:
        w(f"  | {n}")
    w("  deriving DecidableEq, Repr, Inhabited")
    w("")
    w("/-- The C token number (`Include/internal/pycore_token.h`). -/")
    w("def TokKind.num : TokKind → Nat")
    for i, n in enumerate(names):
        w(f"  | .{n} => {i}")
    w("")
    w("/-- Inverse of `TokKind.num`. -/")
    w("def TokKind.ofNum? : Nat → Option TokKind")
    for i, n in enumerate(names):
        w(f"  | {i} => some .{n}")
    w("  | _ => none")
    w("")
    w("/-- Name of the token type, as `token.tok_name` prints it. -/")
    w("def TokKind.name : TokKind → String")
    for n in names:
        w(f'  | .{n} => "{n}"')
    w("")
    w("/-- Exact spelling of an operator token (`token.EXACT_TOKEN_TYPES`). -/")
    w("def TokKind.exact? : TokKind → Option String")
    for n, s in exact.items():
        s2 = s.replace("\\", "\\\\").replace('"', '\\"')
        w(f'  | .{n} => some "{s2}"')
    w("  | _ => none")
    w("")
    w("/-- Every token kind, in file order. -/")
    w("def TokKind.all : _root_.List TokKind :=")
    w("  [" + ", ".join("TokKind." + n for n in names) + "]")
    w("")
    w("/-- Number of token types in `Grammar/Tokens`. -/")
    w(f"def TokKind.count : Nat := {len(names)}")
    w("")
    w("end PyLean.PyGrammar")
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            sys.exit("AstGen.lean is stale")
        print("AstGen.lean matches Python.asdl and Grammar/Tokens")
    else:
        OUT.write_text(text)


if __name__ == "__main__":
    main()
