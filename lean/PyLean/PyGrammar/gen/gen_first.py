#!/usr/bin/env python3
"""Write Peg/RuleFacts.lean: one `NamedRuleStarts` theorem per rule of Grammar/python.gram.

Input is a tsv of `id, name, nullable, types`, printed by evaluating the fixed point of `Closed`
on the grammar data; the same run writes Peg/FirstTable.lean. Nothing here is trusted: Lean checks
each statement against `firstOf`, and `First.lean` checks that table against the grammar.

usage: gen_first.py FIRST_TSV
"""

import ast
import re
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "Peg" / "RuleFacts.lean"
ROOT = Path(os.environ.get("CPYTHON_SRC", Path(__file__).resolve().parents[4] / "vendor" / "cpython-3.15"))


def spellings():
    """Token type number to source spelling or name."""
    names = {}
    ns = {}
    exec((ROOT / "Lib" / "token.py").read_text(), ns)
    exact = {v: k for k, v in ns["EXACT_TOKEN_TYPES"].items()}
    for num, name in ns["tok_name"].items():
        names[num] = exact.get(num, name)
    data = (HERE.parent / "Peg" / "GrammarData.lean").read_text()
    line = next(l for l in data.splitlines() if l.startswith("def keywords"))
    for cps, num in ast.literal_eval(line.split(":=", 1)[1].strip().replace("(", "(")
                                     .replace("[(", "[(")):
        names[num] = "".join(map(chr, cps))
    return names


def main():
    names = spellings()
    out = ["import PyLean.PyGrammar.Peg.First", "",
           "/-! GENERATED by `gen/gen_first.py`. For each rule of `Grammar/python.gram`: if",
           "`callRule` succeeds on it, its first token is of one of these types. Each statement",
           "is checked against the rule's number and name in the grammar data. -/", "",
           "set_option maxRecDepth 100000", "",
           "namespace PyLean.PyGrammar.Peg", "", "open Lexer", "",
           "/-- Rule number `id` is the rule called `name`, and `RuleStarts` holds of it. -/",
           "def NamedRuleStarts (id : Nat) (name : String) (nullable : Bool) (types : List Nat) :"
           " Prop :=", "  (ruleOf id).name = name ∧ RuleStarts id nullable types", "",
           "theorem namedRuleStarts {id : Nat} {name : String} {n : Bool} {t : List Nat}",
           "    (h1 : (ruleOf id).name = name) (h2 : firstOf id = (n, t)) :"
           " NamedRuleStarts id name n t := by",
           "  refine ⟨h1, ?_⟩", "  have := ruleStarts id", "  rw [h2] at this", "  exact this",
           ""]
    seen = 0
    for line in Path(sys.argv[1]).read_text().splitlines():
        rid, name, nullable, types = line.split("\t")
        if name.startswith("_"):
            continue
        seen += 1
        toks = [names.get(t, str(t)) for t in ast.literal_eval(types)]
        shown = ", ".join("`" + re.sub(r"`", "'", t) + "`" for t in toks[:10])
        if len(toks) > 10:
            shown += f", and {len(toks) - 10} more"
        first = ("can match nothing, and otherwise starts with " if nullable == "true"
                 else "starts with ") + (shown or "nothing")
        out += [f"/-- `{name}` {first}. -/",
                f"theorem rule_{name}_starts : NamedRuleStarts {rid} \"{name}\" {nullable} {types} :=",
                "  namedRuleStarts (by decide +kernel) (by decide +kernel)", ""]
    out.append("end PyLean.PyGrammar.Peg")
    OUT.write_text("\n".join(out) + "\n")
    print(seen, "rules")


if __name__ == "__main__":
    main()
