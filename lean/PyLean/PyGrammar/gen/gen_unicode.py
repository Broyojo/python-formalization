#!/usr/bin/env python3
"""Generate lean/PyLean/PyGrammar/UniTables.lean: non-ASCII XID and printable ranges.

The tables are read off the running interpreter (`str.isidentifier`,
`str.isprintable`), so they are what `_PyUnicode_ScanIdentifier` and
`Py_UNICODE_ISPRINTABLE` compute on this build, Unicode tables included.
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "UniTables.lean"


def ranges(pred):
    out, st = [], None
    for i in range(0x80, 0x110000):
        v = pred(i)
        if v and st is None:
            st = i
        if not v and st is not None:
            out.append((st, i - 1))
            st = None
    if st is not None:
        out.append((st, 0x10ffff))
    return out


def surrogate(i):
    return 0xD800 <= i <= 0xDFFF


def emit(w, name, doc, rs):
    w(f"/-- {doc} Flat list `lo₁, hi₁, lo₂, hi₂, …` of inclusive, ascending ranges. -/")
    w(f"def {name} : List Nat := [")
    flat = [str(x) for r in rs for x in r]
    for k in range(0, len(flat), 16):
        w("  " + ", ".join(flat[k:k + 16]) + ("," if k + 16 < len(flat) else ""))
    w("]")
    w("")


def main():
    out = []
    w = out.append
    w(f"/-! GENERATED by `gen/gen_unicode.py` on Python {sys.version.split()[0]}, "
      f"Unicode {unicodedata.unidata_version}. Do not edit. -/")
    w("")
    w("namespace PyLean.PyGrammar")
    w("")
    emit(w, "xidStartRanges", "Non-ASCII `XID_Start`.",
         ranges(lambda i: not surrogate(i) and chr(i).isidentifier()))
    emit(w, "xidContinueRanges", "Non-ASCII `XID_Continue`.",
         ranges(lambda i: not surrogate(i) and ("a" + chr(i)).isidentifier()))
    emit(w, "printableRanges", "Non-ASCII `Py_UNICODE_ISPRINTABLE`.",
         ranges(lambda i: chr(i).isprintable()))
    w("end PyLean.PyGrammar")
    OUT.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
