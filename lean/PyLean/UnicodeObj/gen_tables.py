"""Regenerate Tables.lean from CPython's generated Objects/unicodetype_db.h.

Usage: python3 lean/PyLean/UnicodeObj/gen_tables.py <path to unicodetype_db.h> > lean/PyLean/UnicodeObj/Tables.lean

Each C array becomes one packed `Nat` literal (element i occupies bits
[i*w, (i+1)*w)), because the kernel evaluates `Nat.shiftRight`/`Nat.land` on
literals directly, so `decide` can read the tables. A record of
`_PyUnicode_TypeRecords` packs (upper, lower, title) as 32-bit two's complement,
then decimal, digit (8 bits each) and flags (16 bits), least significant first.
"""
import re
import sys

text = open(sys.argv[1]).read()


def body(name):
    m = re.search(re.escape(name) + r"\[\] = \{(.*?)^\};", text, re.S | re.M)
    return m.group(1)


records = [tuple(int(x) for x in r.split(","))
           for r in re.findall(r"\{([-0-9, ]+)\}", body("_PyUnicode_TypeRecords"))]
extended = [int(x) for x in re.findall(r"\d+", body("_PyUnicode_ExtendedCase"))]
index1 = [int(x) for x in re.findall(r"\d+", body("index1"))]
index2 = [int(x) for x in re.findall(r"\d+", body("index2"))]
shift = int(re.search(r"#define SHIFT (\d+)", text).group(1))


def switch_cases(fn):
    m = re.search(re.escape(fn) + r"\(const Py_UCS4 ch\)\n\{(.*?)^\}", text, re.S | re.M)
    return [int(x, 16) for x in re.findall(r"case 0x([0-9A-Fa-f]+):", m.group(1))]


whitespace = switch_cases("_PyUnicode_IsWhitespace")
linebreak = switch_cases("_PyUnicode_IsLinebreak")


def pack(values, width):
    n = 0
    for i, v in enumerate(values):
        assert 0 <= v < 1 << width
        n |= v << (i * width)
    return hex(n)


def pack_record(r):
    upper, lower, title, decimal, digit, flags = r
    m = (1 << 32) - 1
    return (upper & m) | (lower & m) << 32 | (title & m) << 64 | decimal << 96 | digit << 104 | flags << 112


