"""Regenerate Tables.lean from CPython's generated Objects/unicodetype_db.h.

Usage: python3 lean/PyLean/UnicodeObj/gen_tables.py <path to unicodetype_db.h> > lean/PyLean/UnicodeObj/Tables.lean

Each C array becomes one packed `Nat` literal (element i occupies bits
[i*w, (i+1)*w)), because the kernel evaluates `Nat.shiftRight`/`Nat.land` on
literals directly, so `decide` can read the tables. A record of
`_PyUnicode_TypeRecords` packs (upper, lower, title) as 32-bit two's complement,
then decimal, digit (8 bits each) and flags (16 bits), least significant first.
"""
import re
import sys

text = open(sys.argv[1]).read()


def body(name):
    m = re.search(re.escape(name) + r"\[\] = \{(.*?)^\};", text, re.S | re.M)
    return m.group(1)


records = [tuple(int(x) for x in r.split(","))
           for r in re.findall(r"\{([-0-9, ]+)\}", body("_PyUnicode_TypeRecords"))]
extended = [int(x) for x in re.findall(r"\d+", body("_PyUnicode_ExtendedCase"))]
index1 = [int(x) for x in re.findall(r"\d+", body("index1"))]
index2 = [int(x) for x in re.findall(r"\d+", body("index2"))]
shift = int(re.search(r"#define SHIFT (\d+)", text).group(1))


def switch_cases(fn):
    m = re.search(re.escape(fn) + r"\(const Py_UCS4 ch\)\n\{(.*?)^\}", text, re.S | re.M)
    return [int(x, 16) for x in re.findall(r"case 0x([0-9A-Fa-f]+):", m.group(1))]


whitespace = switch_cases("_PyUnicode_IsWhitespace")
linebreak = switch_cases("_PyUnicode_IsLinebreak")


def pack(values, width):
    n = 0
    for i, v in enumerate(values):
        assert 0 <= v < 1 << width
        n |= v << (i * width)
    return hex(n)


def tree(leaves, lo, hi, indent):
    """A balanced `cond` over the chunk number, so reading a chunk is `log` steps."""
    if hi - lo == 1:
        return leaves[lo]
    mid = (lo + hi) // 2
    pad = "  " * indent
    return (f"cond (Nat.ble {mid} k)\n{pad}  ({tree(leaves, mid, hi, indent + 1)})\n"
            f"{pad}  ({tree(leaves, lo, mid, indent + 1)})")


def chunked(name, doc, values, width, bits):
    leaves = [pack(values[i:i + (1 << bits)], width) for i in range(0, len(values), 1 << bits)]
    return (f"/-- {doc}, cut into chunks of {1 << bits} entries of {width} bits. -/\n"
            f"def {name} (k : Nat) : Nat :=\n  {tree(leaves, 0, len(leaves), 1)}\n")


block_count = len(index2) >> shift
delta_blocks = 0
for b in range(block_count):
    for j in range(1 << shift):
        r = records[index2[(b << shift) + j]]
        if not r[5] & 0x4000 and (r[0] or r[1] or r[2]):
            delta_blocks |= 1 << b


def pack_record(r):
    upper, lower, title, decimal, digit, flags = r
    m = (1 << 32) - 1
    return (upper & m) | (lower & m) << 32 | (title & m) << 64 | decimal << 96 | digit << 104 | flags << 112


print(f"""/-!
GENERATED by gen_tables.py from `Objects/unicodetype_db.h` (CPython 3.14.7). Do not edit.
Each array is cut into small packed literals; see `Ctype.lean` for the readers.
Small chunks matter: the kernel caches intermediate values, and a shift of one
huge literal per code point exhausts its memory limit. Checked for every code
point by `difftest/unicodeobj_diff.py`.
-/

namespace PyLean.UnicodeObj.Tables

/-- `#define SHIFT`, unicodetype_db.h:1758. -/
def shift : Nat := {shift}
/-- Number of entries of `_PyUnicode_TypeRecords`. -/
def recordCount : Nat := {len(records)}
{chunked("typeRecordsChunk", "`_PyUnicode_TypeRecords` (unicodetype_db.h:4)",
         [pack_record(r) for r in records], 128, 4)}
/-- Number of entries of `_PyUnicode_ExtendedCase`. -/
def extendedCaseCount : Nat := {len(extended)}
{chunked("extendedCaseChunk", "`_PyUnicode_ExtendedCase` (unicodetype_db.h:518)", extended, 32, 5)}
{chunked("index1Chunk", "`index1` (unicodetype_db.h:1759)", index1, 16, 6)}
{chunked("index2Chunk", "`index2` (unicodetype_db.h:2972)", index2, 16, 6)}
/-- Number of 64-entry blocks of `index2`. -/
def blockCount : Nat := {block_count}
/-- Bit `b` is set when block `b` has a record with a non-zero case delta. -/
def deltaBlocks : Nat := {hex(delta_blocks)}
/-- The `case` labels of `_PyUnicode_IsWhitespace` (unicodetype_db.h:6676). -/
def whitespace : List Nat := {whitespace}
/-- The `case` labels of `_PyUnicode_IsLinebreak` (unicodetype_db.h:6717). -/
def linebreak : List Nat := {linebreak}

end PyLean.UnicodeObj.Tables""")
