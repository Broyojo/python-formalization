"""Generate FINDINGS.md from bugs/*.yaml and per-version check_bugs logs.

Usage: python3 scripts/gen_findings.py 3.15.2=<log> main=<log>
Each log is check_bugs.py output for one interpreter. Sections are by priority.
The first label is the target: a record that does not reproduce there is left out.
The verdict on what to file stays a human decision; this only states the facts.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def field(text, key):
    match = re.search(rf"^{key}:\s*(.*)$", text, re.M)
    return match.group(1).strip().strip("\"'") if match else ""


def duplicates(text):
    block = re.search(r"^duplicates:\n((?:[ \t].*\n)+)", text, re.M)
    return re.findall(r"number:\s*(\d+)[^}]*?relation:\s*\"?([^,}\"]*)", block.group(1)) if block else []


def main():
    versions = [arg.split("=", 1) for arg in sys.argv[1:]]
    results = {}
    for label, log in versions:
        for line in Path(log).read_text().splitlines():
            match = re.match(r"(REPRODUCED|NOT REPRODUCED)\s+(\S+)", line)
            if match:
                results.setdefault(match.group(2), {})[label] = match.group(1) == "REPRODUCED"

    rows = []
    for path in sorted((ROOT / "bugs").glob("*.yaml")):
        text = path.read_text(encoding="utf8")
        related = [f"#{n}" for n, rel in duplicates(text) if "duplicate" in rel.lower()]
        if "duplicate" in field(text, "kind") or field(text, "status") == "duplicate":
            related = related or ["yes"]
        rows.append((field(text, "priority"), path.stem, field(text, "kind"), field(text, "title"), related,
                     results.get(path.stem, {})))

    labels = [label for label, _ in versions]
    target = labels[0]
    total = len(rows)
    rows = [r for r in rows if r[5].get(target)]
    live = len(rows)
    out = ["# Findings", "",
           "Generated by `scripts/gen_findings.py`. Nothing here has been filed. Priorities are the",
           "recording agent's; a person decides what goes upstream. `yes` means the reproducer fired.", "",
           f"{live} records reproduce on {target}, the target. {total - live} others do not and are left out.", ""]
    for priority in sorted({r[0] for r in rows}):
        out += [f"## {priority}", "", "| record | kind | " + " | ".join(labels) + " | duplicate of | title |",
                "|---|---|" + "---|" * len(labels) + "---|---|"]
        for prio, name, kind, title, related, seen in rows:
            if prio == priority:
                cells = ["yes" if seen.get(l) else ("no" if l in seen else "?") for l in labels]
                out.append(f"| `{name}` | {kind} | " + " | ".join(cells) +
                           f" | {' '.join(related)} | {title.replace('|', '/')} |")
        out.append("")
    (ROOT / "FINDINGS.md").write_text("\n".join(out))
    print(f"wrote FINDINGS.md: {len(rows)} records, {live} live")


if __name__ == "__main__":
    main()
